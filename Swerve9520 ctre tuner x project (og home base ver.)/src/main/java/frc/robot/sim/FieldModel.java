package frc.robot.sim;

import java.io.File;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;

import edu.wpi.first.apriltag.AprilTagFieldLayout;
import edu.wpi.first.apriltag.AprilTagFields;
import edu.wpi.first.math.geometry.Translation2d;
import edu.wpi.first.wpilibj.Filesystem;

/**
 * ★ NEW (sim only) — the 2026 field for the Java sim: AprilTags (same WPILib
 * layout as VisionSubsystem) plus the solid field elements from
 * deploy/sim/field-2026.json (generated by sim-ui/scripts/gen-field.mjs —
 * the same geometry the web UI draws). Used to block camera sightlines.
 */
public class FieldModel {
    public final AprilTagFieldLayout tags = AprilTagFieldLayout.loadField(AprilTagFields.k2026RebuiltAndymark);
    public final double length;
    public final double width;
    /** Element polygons ({x0,y0,x1,y1,...}) that block camera sightlines — the HUBs. */
    private final List<double[]> solids = new ArrayList<>();
    /** Bounding box {minX, minY, maxX, maxY} of every element, by id (e.g. "blue-depot"). */
    private final Map<String, double[]> boxes = new HashMap<>();
    /** Boxes FUEL bounces off: HUBs, TOWERs and OUTPOSTs. BUMPs and TRENCHes let it roll over/under. */
    public final List<double[]> fuelSolids = new ArrayList<>();
    private Translation2d hubBlue = new Translation2d(4.6115, 4.0215);
    private Translation2d hubRed  = new Translation2d(11.9065, 4.0215);
    /** HUB opening: a hexagon, flat sides facing ±Y. Across the flats, inside (field drawings: 41.73 in). */
    public double hubOpeningAcrossFlatsM = 1.0599;

    public FieldModel() {
        length = tags.getFieldLength();
        width = tags.getFieldWidth();
        try {
            JsonNode root = new ObjectMapper().readTree(new File(Filesystem.getDeployDirectory(), "sim/field-2026.json"));
            JsonNode v = root.path("variants").path("andymark");
            JsonNode hc = v.path("hubCenters");
            hubBlue = new Translation2d(hc.path("blue").get(0).asDouble(), hc.path("blue").get(1).asDouble());
            hubRed  = new Translation2d(hc.path("red").get(0).asDouble(),  hc.path("red").get(1).asDouble());
            hubOpeningAcrossFlatsM = root.path("hubOpening").path("acrossFlatsM").asDouble(hubOpeningAcrossFlatsM);
            for (JsonNode el : v.path("elements")) {
                JsonNode poly = el.path("poly");
                double[] flat = new double[poly.size() * 2];
                double[] box = { Double.MAX_VALUE, Double.MAX_VALUE, -Double.MAX_VALUE, -Double.MAX_VALUE };
                for (int i = 0; i < poly.size(); i++) {
                    flat[2 * i] = poly.get(i).get(0).asDouble();
                    flat[2 * i + 1] = poly.get(i).get(1).asDouble();
                    box[0] = Math.min(box[0], flat[2 * i]);     box[1] = Math.min(box[1], flat[2 * i + 1]);
                    box[2] = Math.max(box[2], flat[2 * i]);     box[3] = Math.max(box[3], flat[2 * i + 1]);
                }
                String id = el.path("id").asText();
                String type = el.path("type").asText();
                boxes.put(id, box);
                if ("solid".equals(type) || id.endsWith("-outpost")) fuelSolids.add(box);
                if (!"solid".equals(type)) continue;
                // TOWER: open uprights + floor plate — cameras see its wall-mounted tags
                if (!el.path("blocksVision").asBoolean(true)) continue;
                solids.add(flat);
            }
        } catch (Exception e) {
            System.out.println("[Sim] field-2026.json not loaded (" + e.getMessage() + ") — no sightline blocking");
        }
    }

    public Translation2d hubCenter(boolean red) { return red ? hubRed : hubBlue; }

    /**
     * True if a ball of radius {@code ballRadiusM} whose center crosses the HUB
     * rim at (x, y) fits through the opening (it doesn't touch the rim).
     */
    public boolean inHubOpening(boolean red, double x, double y, double ballRadiusM) {
        Translation2d c = hubCenter(red);
        return insideHexagon(x - c.getX(), y - c.getY(), hubOpeningAcrossFlatsM / 2 - ballRadiusM);
    }

    /**
     * Point (dx, dy) inside a regular hexagon centered on the origin with flat
     * sides facing ±Y (corners on ±X) and the given inradius (center to a flat).
     * The other two pairs of flats face ±30° from the X axis.
     */
    static boolean insideHexagon(double dx, double dy, double inradius) {
        if (inradius <= 0) return false;
        double ax = Math.abs(dx), ay = Math.abs(dy);
        return ay <= inradius && ax * Math.sqrt(3) / 2 + ay / 2 <= inradius;
    }

    /** Bounding box {minX, minY, maxX, maxY} of an element (e.g. "red-depot"), or null if unknown. */
    public double[] box(String id) { return boxes.get(id); }

    /** True if the 2D segment a→b passes through a sightline-blocking element (HUB). */
    public boolean blocked(double ax, double ay, double bx, double by) {
        for (double[] p : solids) {
            int n = p.length / 2;
            for (int i = 0; i < n; i++) {
                int j = (i + 1) % n;
                if (segmentsCross(ax, ay, bx, by, p[2 * i], p[2 * i + 1], p[2 * j], p[2 * j + 1])) return true;
            }
        }
        return false;
    }

    private static boolean segmentsCross(double ax, double ay, double bx, double by,
                                         double cx, double cy, double dx, double dy) {
        double d1 = cross(cx, cy, dx, dy, ax, ay), d2 = cross(cx, cy, dx, dy, bx, by);
        double d3 = cross(ax, ay, bx, by, cx, cy), d4 = cross(ax, ay, bx, by, dx, dy);
        return ((d1 > 0) != (d2 > 0)) && ((d3 > 0) != (d4 > 0));
    }

    private static double cross(double ax, double ay, double bx, double by, double px, double py) {
        return (bx - ax) * (py - ay) - (by - ay) * (px - ax);
    }
}
