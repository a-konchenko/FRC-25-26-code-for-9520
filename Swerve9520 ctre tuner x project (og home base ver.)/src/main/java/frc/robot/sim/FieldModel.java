package frc.robot.sim;

import java.io.File;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;

import edu.wpi.first.apriltag.AprilTagFieldLayout;
import edu.wpi.first.apriltag.AprilTagFields;
import edu.wpi.first.math.geometry.Pose2d;
import edu.wpi.first.math.geometry.Rotation2d;
import edu.wpi.first.math.geometry.Translation2d;
import edu.wpi.first.math.util.Units;
import edu.wpi.first.wpilibj.Filesystem;

/**
 * ★ NEW (sim only) — the field the simulator runs on. Two are built in:
 *
 *  REBUILT_2026 ("2026", the default): the 2026 game field — AprilTags from
 *    the same WPILib layout VisionSubsystem loads (AndyMark) plus the solid
 *    field elements from deploy/sim/field-2026.json (generated by
 *    sim-ui/scripts/gen-field.mjs — the same geometry the web UI draws).
 *    The elements block camera sightlines and bounce FUEL.
 *
 *  B8 ("b8"): Team 9520's practice space, a 15 ft × 11 ft rectangle from
 *    deploy/sim/field-b8.json (same generator). No AprilTags and no field
 *    elements yet, so the cameras see nothing and no FUEL is staged:
 *    driving practice only. When the space gets targets, add the elements
 *    in gen-field.mjs and the tags here (the B8 branch of the constructor).
 *
 * The web UI picks the field (/Sim/Control/field → SimManager.setField).
 */
public class FieldModel {
    public static final String REBUILT_2026 = "2026";
    public static final String B8 = "b8";
    /** B8 if deploy/sim/field-b8.json can't be read: 15 ft × 11 ft, exactly. */
    static final double kB8LengthM = Units.feetToMeters(15.0);
    static final double kB8WidthM  = Units.feetToMeters(11.0);

    public final String id;
    /** For the console and the UI. */
    public final String name;
    public final AprilTagFieldLayout tags;
    public final double length;
    public final double width;
    /** Element polygons ({x0,y0,x1,y1,...}) that block camera sightlines — the HUBs. */
    private final List<double[]> solids = new ArrayList<>();
    /** Bounding box {minX, minY, maxX, maxY} of every element, by id (e.g. "blue-depot"). */
    private final Map<String, double[]> boxes = new HashMap<>();
    /** Boxes FUEL bounces off: HUBs, TOWERs and OUTPOSTs. BUMPs and TRENCHes let it roll over/under. */
    public final List<double[]> fuelSolids = new ArrayList<>();
    private Translation2d hubBlue = new Translation2d(4.6115, 4.0215);
    private Translation2d hubRed  = new Translation2d(11.9065, 4.0215);
    /** False on a practice field without HUBs: no FUEL is staged and nothing can score. */
    private final boolean gamePieces;
    private final Pose2d defaultStart;

    /** The 2026 game field. */
    public FieldModel() {
        this(REBUILT_2026);
    }

    /** @param id {@link #REBUILT_2026} or {@link #B8} */
    public FieldModel(String id) {
        this.id = id;
        if (B8.equals(id)) {
            JsonNode root = read("sim/field-b8.json");
            name   = text(root, "game", "B8 practice field");
            length = number(root, "length", kB8LengthM);
            width  = number(root, "width", kB8WidthM);
            tags   = new AprilTagFieldLayout(new ArrayList<>(), length, width); // no tags yet
            if (root != null) loadElements(root.path("elements"));
            gamePieces   = false;
            defaultStart = new Pose2d(length / 2, width / 2, Rotation2d.kZero); // the middle, facing +X
        } else if (REBUILT_2026.equals(id)) {
            name   = "2026 REBUILT (AndyMark)";
            tags   = AprilTagFieldLayout.loadField(AprilTagFields.k2026RebuiltAndymark);
            length = tags.getFieldLength();
            width  = tags.getFieldWidth();
            JsonNode root = read("sim/field-2026.json");
            if (root != null) {
                JsonNode v = root.path("variants").path("andymark");
                JsonNode hc = v.path("hubCenters");
                if (hc.path("blue").size() >= 2 && hc.path("red").size() >= 2) {
                    hubBlue = new Translation2d(hc.path("blue").get(0).asDouble(), hc.path("blue").get(1).asDouble());
                    hubRed  = new Translation2d(hc.path("red").get(0).asDouble(),  hc.path("red").get(1).asDouble());
                }
                loadElements(v.path("elements"));
            }
            gamePieces = true;
            double[] s = SimRobotConstants.kDefaultStartPose;
            defaultStart = new Pose2d(s[0], s[1], Rotation2d.fromRadians(s[2]));
        } else {
            throw new IllegalArgumentException("Unknown field '" + id + "' (use \"" + REBUILT_2026 + "\" or \"" + B8 + "\")");
        }
    }

    /** Parses a deploy file; null (with a console note) if it can't be read. */
    private static JsonNode read(String deployRelative) {
        try {
            return new ObjectMapper().readTree(new File(Filesystem.getDeployDirectory(), deployRelative));
        } catch (Exception e) {
            System.out.println("[Sim] " + deployRelative + " not loaded (" + e.getMessage() + ") — built-in size, no field elements");
            return null;
        }
    }

    private static String text(JsonNode node, String key, String dflt) {
        return node != null ? node.path(key).asText(dflt) : dflt;
    }

    private static double number(JsonNode node, String key, double dflt) {
        return node != null ? node.path(key).asDouble(dflt) : dflt;
    }

    /** Elements with the generator's schema: id, type, poly [[x, y], …], blocksVision. */
    private void loadElements(JsonNode elements) {
        try {
            for (JsonNode el : elements) {
                JsonNode poly = el.path("poly");
                double[] flat = new double[poly.size() * 2];
                double[] box = { Double.MAX_VALUE, Double.MAX_VALUE, -Double.MAX_VALUE, -Double.MAX_VALUE };
                for (int i = 0; i < poly.size(); i++) {
                    flat[2 * i] = poly.get(i).get(0).asDouble();
                    flat[2 * i + 1] = poly.get(i).get(1).asDouble();
                    box[0] = Math.min(box[0], flat[2 * i]);     box[1] = Math.min(box[1], flat[2 * i + 1]);
                    box[2] = Math.max(box[2], flat[2 * i]);     box[3] = Math.max(box[3], flat[2 * i + 1]);
                }
                String id = el.path("id").asText();
                String type = el.path("type").asText();
                boxes.put(id, box);
                if ("solid".equals(type) || id.endsWith("-outpost")) fuelSolids.add(box);
                if (!"solid".equals(type)) continue;
                // TOWER: open uprights + floor plate — cameras see its wall-mounted tags
                if (!el.path("blocksVision").asBoolean(true)) continue;
                solids.add(flat);
            }
        } catch (Exception e) {
            System.out.println("[Sim] field elements not loaded (" + e.getMessage() + ") — no sightline blocking");
        }
    }

    /** True on the game field (HUBs to score into, FUEL to stage); false on the empty practice field. */
    public boolean hasGamePieces() { return gamePieces; }

    /** Where the robot is put when the sim starts or the field is switched. */
    public Pose2d defaultStartPose() { return defaultStart; }

    public Translation2d hubCenter(boolean red) { return red ? hubRed : hubBlue; }

    /** Bounding box {minX, minY, maxX, maxY} of an element (e.g. "red-depot"), or null if unknown. */
    public double[] box(String id) { return boxes.get(id); }

    /** True if the 2D segment a→b passes through a sightline-blocking element (HUB). */
    public boolean blocked(double ax, double ay, double bx, double by) {
        for (double[] p : solids) {
            int n = p.length / 2;
            for (int i = 0; i < n; i++) {
                int j = (i + 1) % n;
                if (segmentsCross(ax, ay, bx, by, p[2 * i], p[2 * i + 1], p[2 * j], p[2 * j + 1])) return true;
            }
        }
        return false;
    }

    private static boolean segmentsCross(double ax, double ay, double bx, double by,
                                         double cx, double cy, double dx, double dy) {
        double d1 = cross(cx, cy, dx, dy, ax, ay), d2 = cross(cx, cy, dx, dy, bx, by);
        double d3 = cross(ax, ay, bx, by, cx, cy), d4 = cross(ax, ay, bx, by, dx, dy);
        return ((d1 > 0) != (d2 > 0)) && ((d3 > 0) != (d4 > 0));
    }

    private static double cross(double ax, double ay, double bx, double by, double px, double py) {
        return (bx - ax) * (py - ay) - (by - ay) * (px - ax);
    }
}
